-- ---------------------------------------------------------------------------------------------
-- Per-user, per-game rating and record
-- ---------------------------------------------------------------------------------------------
CREATE TABLE player_game_stats (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    game_id         BIGINT       NOT NULL REFERENCES games (id),
    rating          INTEGER      NOT NULL DEFAULT 1000,
    peak_rating     INTEGER      NOT NULL DEFAULT 1000,
    ranked_wins     INTEGER      NOT NULL DEFAULT 0,
    ranked_losses   INTEGER      NOT NULL DEFAULT 0,
    ranked_draws    INTEGER      NOT NULL DEFAULT 0,
    casual_wins     INTEGER      NOT NULL DEFAULT 0,
    casual_losses   INTEGER      NOT NULL DEFAULT 0,
    casual_draws    INTEGER      NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_player_game_stats_user_game UNIQUE (user_id, game_id),
    CONSTRAINT ck_player_game_stats_peak CHECK (peak_rating >= rating),
    CONSTRAINT ck_player_game_stats_counts CHECK (
        ranked_wins >= 0 AND ranked_losses >= 0 AND ranked_draws >= 0
        AND casual_wins >= 0 AND casual_losses >= 0 AND casual_draws >= 0)
);

-- Leaderboard: top ratings per game.
CREATE INDEX ix_player_game_stats_leaderboard ON player_game_stats (game_id, rating DESC, user_id);

-- ---------------------------------------------------------------------------------------------
-- Matches
-- ---------------------------------------------------------------------------------------------
CREATE TABLE matches (
    id                  UUID         PRIMARY KEY,
    game_id             BIGINT       NOT NULL REFERENCES games (id),
    mode                VARCHAR(16)  NOT NULL,
    status              VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    end_reason          VARCHAR(16),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    started_at          TIMESTAMPTZ,
    ended_at            TIMESTAMPTZ,
    -- Set exactly once, in the same transaction that writes rating_history (idempotency guard).
    ratings_applied_at  TIMESTAMPTZ,
    version             BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_matches_mode CHECK (mode IN ('RANKED', 'CASUAL')),
    CONSTRAINT ck_matches_status CHECK (status IN ('PENDING', 'IN_PROGRESS', 'COMPLETED', 'ABANDONED', 'CANCELLED')),
    CONSTRAINT ck_matches_end_reason CHECK (end_reason IS NULL OR end_reason IN ('NORMAL', 'FORFEIT', 'DISCONNECT', 'TIMEOUT')),
    CONSTRAINT ck_matches_ended CHECK ((status IN ('COMPLETED', 'ABANDONED', 'CANCELLED')) = (ended_at IS NOT NULL)),
    CONSTRAINT ck_matches_ratings_ranked_only CHECK (ratings_applied_at IS NULL OR (mode = 'RANKED' AND status = 'COMPLETED'))
);

CREATE INDEX ix_matches_status ON matches (status) WHERE status IN ('PENDING', 'IN_PROGRESS');
CREATE INDEX ix_matches_game_created ON matches (game_id, created_at DESC);

CREATE TABLE match_players (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id       UUID         NOT NULL REFERENCES matches (id) ON DELETE CASCADE,
    user_id        BIGINT       NOT NULL REFERENCES users (id),
    seat           SMALLINT     NOT NULL,
    result         VARCHAR(8),
    score          INTEGER,
    rating_before  INTEGER,
    rating_after   INTEGER,
    joined_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_match_players_match_user UNIQUE (match_id, user_id),
    CONSTRAINT uq_match_players_match_seat UNIQUE (match_id, seat),
    CONSTRAINT ck_match_players_seat CHECK (seat >= 0),
    CONSTRAINT ck_match_players_result CHECK (result IS NULL OR result IN ('WIN', 'LOSS', 'DRAW'))
);

-- Match history for a player.
CREATE INDEX ix_match_players_user ON match_players (user_id, joined_at DESC);

-- ---------------------------------------------------------------------------------------------
-- Rating history: one row per player per rated match.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE rating_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    game_id        BIGINT       NOT NULL REFERENCES games (id),
    match_id       UUID         NOT NULL REFERENCES matches (id),
    rating_before  INTEGER      NOT NULL,
    rating_after   INTEGER      NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- A match can change a player's rating at most once.
    CONSTRAINT uq_rating_history_match_user UNIQUE (match_id, user_id)
);

CREATE INDEX ix_rating_history_user_game ON rating_history (user_id, game_id, created_at DESC);

-- ---------------------------------------------------------------------------------------------
-- Match events: ordered, server-validated log of what happened in a match (audit / replay).
-- ---------------------------------------------------------------------------------------------
CREATE TABLE match_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id    UUID         NOT NULL REFERENCES matches (id) ON DELETE CASCADE,
    sequence    INTEGER      NOT NULL,
    user_id     BIGINT       REFERENCES users (id),
    event_type  VARCHAR(64)  NOT NULL,
    payload     JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_match_events_match_sequence UNIQUE (match_id, sequence),
    CONSTRAINT ck_match_events_sequence CHECK (sequence >= 0)
);

-- ---------------------------------------------------------------------------------------------
-- Future features: friendships and direct game invitations.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE friendships (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id  BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    addressee_id  BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status        VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    responded_at  TIMESTAMPTZ,
    CONSTRAINT ck_friendships_not_self CHECK (requester_id <> addressee_id),
    CONSTRAINT ck_friendships_status CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'BLOCKED'))
);

-- One relationship per pair regardless of who asked.
CREATE UNIQUE INDEX uq_friendships_pair ON friendships (LEAST(requester_id, addressee_id), GREATEST(requester_id, addressee_id));
CREATE INDEX ix_friendships_addressee ON friendships (addressee_id, status);

CREATE TABLE game_invitations (
    id            UUID         PRIMARY KEY,
    game_id       BIGINT       NOT NULL REFERENCES games (id),
    inviter_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    invitee_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    mode          VARCHAR(16)  NOT NULL,
    status        VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    match_id      UUID         REFERENCES matches (id),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at    TIMESTAMPTZ  NOT NULL,
    responded_at  TIMESTAMPTZ,
    CONSTRAINT ck_game_invitations_not_self CHECK (inviter_id <> invitee_id),
    CONSTRAINT ck_game_invitations_mode CHECK (mode IN ('RANKED', 'CASUAL')),
    CONSTRAINT ck_game_invitations_status CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'EXPIRED', 'CANCELLED'))
);

CREATE INDEX ix_game_invitations_invitee ON game_invitations (invitee_id, status);
