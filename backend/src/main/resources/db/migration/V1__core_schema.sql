-- Duelyard core schema.
-- Conventions: snake_case, timestamptz for all instants, enums stored as constrained varchar
-- (portable and easy to extend with a migration), optimistic-lock "version" columns on rows that
-- are updated concurrently.

-- ---------------------------------------------------------------------------------------------
-- Users
-- ---------------------------------------------------------------------------------------------
CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cognito_sub         VARCHAR(128)  NOT NULL,
    username            VARCHAR(20)   NOT NULL,
    email               VARCHAR(320)  NOT NULL,
    avatar_url          VARCHAR(1024),
    profile_visibility  VARCHAR(16)   NOT NULL DEFAULT 'PUBLIC',
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version             BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uq_users_cognito_sub UNIQUE (cognito_sub),
    CONSTRAINT ck_users_username_format CHECK (username ~ '^[A-Za-z0-9_]{3,20}$'),
    CONSTRAINT ck_users_profile_visibility CHECK (profile_visibility IN ('PUBLIC', 'PRIVATE'))
);

-- Usernames are unique case-insensitively ("Alice" and "alice" cannot coexist).
CREATE UNIQUE INDEX uq_users_username_ci ON users (lower(username));
CREATE INDEX ix_users_email ON users (lower(email));

-- ---------------------------------------------------------------------------------------------
-- Games. Each row must correspond to a GameModule bean (verified at startup).
-- ---------------------------------------------------------------------------------------------
CREATE TABLE games (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug          VARCHAR(32)  NOT NULL,
    display_name  VARCHAR(64)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_games_slug UNIQUE (slug)
);

